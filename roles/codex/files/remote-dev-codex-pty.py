#!/usr/bin/env python3
"""Run Codex in a PTY and forward only its localhost OAuth URL."""
from __future__ import annotations
import os, pty, re, select, subprocess, sys, termios, tty, struct, fcntl
from urllib.parse import parse_qs, unquote, urlsplit

if len(sys.argv) < 5:
    raise SystemExit(2)
sender, target, nonce, real = sys.argv[1:5]
args = sys.argv[5:]
# Codex renders the link through a TUI and may insert ANSI/OSC hyperlink
# sequences, hard-wrap it at the terminal width, or change whether the
# localhost callback separator is URL-encoded.  Do not depend on the visual
# ``originator`` suffix: the OAuth request is complete once its PKCE/state
# parameters and loopback redirect are present.
oauth_prefix = b"https://auth.openai.com/oauth/authorize?"
oauth_candidate_re = re.compile(
    rb"https://auth\.openai\.com/oauth/authorize\?"
    rb"[A-Za-z0-9._~:/?%&=+\-]+"
)
osc_hyperlink_re = re.compile(
    rb"\x1b\]8;;(https://auth\.openai\.com/oauth/authorize\?[^\x07\x1b]+)"
    rb"(?:\x07|\x1b\\)"
)
ansi_re = re.compile(rb"\x1b(?:\][^\x07]*(?:\x07|\x1b\\)|\[[0-?]*[ -/]*[@-~])")


def _complete_oauth_urls(raw: bytes) -> list[str]:
    """Return complete authorize URLs from a possibly fragmented PTY buffer."""
    # OSC-8 contains the real href even when the visible link is abbreviated;
    # preserve it before removing terminal control sequences.
    candidates = list(osc_hyperlink_re.findall(raw))
    cleaned = ansi_re.sub(b"", raw).replace(b"\r", b"").replace(b"\n", b"")
    cleaned = re.sub(rb"[ \t]+", b"", cleaned)
    candidates.extend(match.group(0) for match in oauth_candidate_re.finditer(cleaned))
    complete: list[str] = []
    for candidate in candidates:
        value = candidate.decode("ascii", "ignore").rstrip(".,;)]}")
        try:
            parsed = urlsplit(value)
            params = parse_qs(parsed.query, keep_blank_values=True)
        except ValueError:
            continue
        redirect = unquote(params.get("redirect_uri", [""])[0])
        # These fields are generated by Codex's PKCE flow.  Requiring them
        # prevents opening a truncated URL from an intermediate TUI redraw.
        required = ("response_type", "client_id", "redirect_uri", "code_challenge", "state")
        if (
            parsed.scheme == "https"
            and parsed.netloc == "auth.openai.com"
            and parsed.path == "/oauth/authorize"
            and all(params.get(key, [""])[0] for key in required)
            and len(params["code_challenge"][0]) >= 20
            and len(params["state"][0]) >= 16
            and "localhost:1455" in redirect
        ):
            if value not in complete:
                complete.append(value)
    return complete


pid, fd = pty.fork()
if pid == 0:
    os.execv(real, [real, *args])
seen: set[str] = set()
url_buffer = b""
old = termios.tcgetattr(0) if os.isatty(0) else None
if old:
    tty.setraw(0)
    try:
        size = fcntl.ioctl(0, termios.TIOCGWINSZ, b"\0" * 8)
        fcntl.ioctl(fd, termios.TIOCSWINSZ, size)
    except OSError:
        pass
try:
  while True:
    sources = [fd] + ([0] if old else [])
    ready, _, _ = select.select(sources, [], [], 0.2)
    if old and 0 in ready:
        try:
            user_data = os.read(0, 8192)
            if user_data:
                os.write(fd, user_data)
        except OSError:
            pass
    if fd in ready:
        try:
            data = os.read(fd, 8192)
        except OSError:
            data = b""
        if data:
            os.write(1, data)
            url_buffer = (url_buffer + data)[-32768:]
            # TUI redraws can repeat the authorize link.  Keep only the most
            # recent URL start so fragments from an earlier redraw cannot be
            # concatenated into an invalid request.
            latest = url_buffer.rfind(oauth_prefix)
            if latest > 0:
                url_buffer = url_buffer[latest:]
            for value in _complete_oauth_urls(url_buffer):
                if value not in seen:
                    seen.add(value)
                    subprocess.run([sys.executable, sender, "CODEX_OAUTH_URL", target, nonce, value], check=False)
                    url_buffer = b""
    try:
        result_pid, status = os.waitpid(pid, os.WNOHANG)
    except ChildProcessError:
        break
    if result_pid == pid:
        raise SystemExit(os.waitstatus_to_exitcode(status))
finally:
    if old:
        termios.tcsetattr(0, termios.TCSADRAIN, old)
